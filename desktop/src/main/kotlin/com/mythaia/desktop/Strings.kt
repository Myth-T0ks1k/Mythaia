/** The UI languages the desktop app ships. */
enum class Lang(val code: String, val title: String) {
    RU("ru", "Русский"),
    EN("en", "English");

    companion object {
        fun of(code: String?): Lang = entries.firstOrNull { it.code == code } ?: system()
        fun system(): Lang = if (Locale.getDefault().language == "ru") RU else EN
    }
}

